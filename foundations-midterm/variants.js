// More questions. Each one joins a `family`; Start draws one question per family,
// so adding to an existing family adds variety without making the quiz longer;
// a new family adds one question to every quiz.
// mc: the first choice is the correct one (choices are shuffled on display).
// short: groups are [label, ...keywords]; one match per group earns a point.
// code: accepted answers are compared after removing spaces and normalizing quotes.

const counters = {};
const id = family => `${family}-x${(counters[family] = (counters[family] ?? 0) + 1)}`;
const mc = ({family, choices, ...q}) => ({
  id: id(family), family, type: 'mc', ...q,
  choices: choices.map((text, i) => ({id: String(i), text})), answer: '0',
});
const short = ({family, groups, ...q}) => ({
  id: id(family), family, type: 'short', ...q,
  groups: groups.map(([label, ...any]) => ({label, any})),
});
const code = ({family, ...q}) => ({id: id(family), family, type: 'code', ...q});
// Typed output: surrounding quotes on the student's answer are ignored.
const output = q => code({...q, output: true});
const withUrlVar = urls => urls.flatMap(u => [u, `url = '${u}'`]);

